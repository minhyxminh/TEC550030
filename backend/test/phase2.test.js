import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('Phase 2: global QR, daily GP, chat authorization, pagination and retry safety', async t => {
  const db = new PGlite();
  t.after(() => db.close());
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create table auth.users(id uuid primary key,raw_user_meta_data jsonb default '{}');
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text);
    alter table storage.objects enable row level security;
    grant usage on schema auth,storage to authenticated,anon;
    grant insert,select on storage.objects to authenticated;`);
  for (const file of ['001_initial_schema','002_workflows','003_media_hourly_qr','004_phase1_stability',
    '005_phase1_home_gym_bridge','006_remove_auto_gym_and_add_cancellation','007_phase2a_gym_branches',
    '008_global_qr_checkin','009_chat','010_cancel_membership_clear_home_gym']) {
    await db.exec(await readFile(new URL(`../../supabase/migrations/${file}.sql`, import.meta.url), 'utf8'));
    if (file === '001_initial_schema') await db.exec(await readFile(new URL('../../supabase/seed.sql', import.meta.url),'utf8'));
  }
  const member = crypto.randomUUID(), other = crypto.randomUUID(), admin = crypto.randomUUID();
  for (const id of [member,other,admin]) await db.query('insert into auth.users(id) values($1)',[id]);
  await db.query("update public.users set role='ADMIN' where id=$1",[admin]);
  await db.query("update public.users set active_membership_id='10000000-0000-4000-8000-000000000001',membership_expires_at=now()+interval '1 day' where id=$1",[member]);
  const hash = 'a'.repeat(64);
  const qr = (await db.query("insert into public.qr_tokens(gym_id,token_hash,expires_at) values('1',$1,now()+interval '1 hour') returning id",[hash])).rows[0];
  await db.query("insert into public.qr_tokens(gym_id,token_hash,expires_at) values('1',$1,now()+interval '1 hour')",['b'.repeat(64)]);
  const as = async id => db.exec(`reset role; set role authenticated; set request.jwt.claim.sub='${id}'`);
  const command = async (action,payload={}) => (await db.query('select public.gymflow_command($1,$2) as data',[action,JSON.stringify(payload)])).rows[0].data;
  const chat = async (action,payload={}) => (await db.query('select public.gymflow_chat($1,$2) as data',[action,JSON.stringify(payload)])).rows[0].data;
  await as(member);
  await assert.rejects(command('check_in',{token_hash:hash}),/GYM_REQUIRED/);
  let previous;
  for (const gym of ['q6','1','q7']) {
    await db.query('select public.gymflow_select_home_gym($1)',[gym]);
    const visit = await command('check_in',{token_hash:hash});
    assert.equal(visit.session.gym_id,gym);
    assert.equal(visit.session.qr_token_id,qr.id);
    assert.equal(visit.points_earned,previous ? 0 : 5);
    const retry = await command('check_in',{token_hash:hash});
    assert.equal(retry.session.id,visit.session.id);
    assert.equal(retry.points_earned,0);
    await assert.rejects(command('check_in',{token_hash:'b'.repeat(64)}),/ALREADY_CHECKED_IN/);
    const occupancy = (await db.query("select public.gymflow_read('occupancy',$1) as data",[JSON.stringify({gym_id:gym})])).rows[0].data;
    assert.equal(occupancy.count,1);
    await command('check_out',{session_id:visit.session.id});
    await command('check_out',{session_id:visit.session.id});
    previous = visit;
  }
  assert.equal(Number((await db.query('select public.get_my_point_balance() as n')).rows[0].n),5);
  await as(other);
  await db.query("select public.gymflow_select_home_gym('1')");
  await assert.rejects(command('check_in',{token_hash:hash}),/MEMBERSHIP_REQUIRED/);
  await as(member);
  await assert.rejects(command('check_in',{token_hash:'f'.repeat(64)}),/INVALID_QR/);
  await db.exec('reset role');
  await db.query("update public.qr_tokens set revoked_at=now() where id=$1",[qr.id]);
  await as(member);
  await assert.rejects(command('check_in',{token_hash:hash}),/INVALID_QR/);
  await db.exec('reset role');
  await db.query("update public.qr_tokens set revoked_at=null,issued_at=now()-interval '2 hours',expires_at=now()-interval '1 hour' where id=$1",[qr.id]);
  await as(member);
  await assert.rejects(command('check_in',{token_hash:hash}),/INVALID_QR/);
  await db.exec('reset role');
  await assert.rejects(db.query('insert into public.gym_sessions(user_id,gym_id,qr_token_id) values($1,$2,$3)',[member,'1',qr.id]),/WRONG_GYM/);

  await as(member);
  const conv = await chat('open');
  assert.equal((await chat('open')).id,conv.id);
  const payload = {conversation_id:conv.id,content:'Xin chào',client_id:crypto.randomUUID()};
  const first = await chat('send',payload);
  assert.equal((await chat('send',payload)).id,first.id);
  await assert.rejects(chat('send',{...payload,content:'Changed'}),/REQUEST_CONFLICT/);
  await assert.rejects(chat('send',{...payload,content:'   ',client_id:crypto.randomUUID()}),/INVALID_INPUT/);
  await assert.rejects(chat('send',{...payload,content:'x'.repeat(2001),client_id:crypto.randomUUID()}),/INVALID_INPUT/);
  await assert.rejects(chat('inbox'),/FORBIDDEN/);
  await assert.rejects(db.query('insert into public.messages(conversation_id,sender_id,content,client_id) values($1,$2,$3,$4)',[conv.id,admin,'spoof',crypto.randomUUID()]),/permission denied/);
  await as(other);
  assert.equal((await db.query('select * from public.messages')).rows.length,0);
  assert.equal((await db.query('select * from public.conversations')).rows.length,0);
  for (const action of ['messages','send','read']) await assert.rejects(chat(action,payload),/NOT_FOUND/);
  await as(admin);
  const inbox = await chat('inbox');
  assert.equal(inbox.conversations[0].id,conv.id);
  assert.equal(inbox.conversations[0].unread,1);
  assert.equal((await db.query('select * from public.messages')).rows.length,1);
  await chat('read',{conversation_id:conv.id,through:first.sequence});
  assert.equal((await chat('inbox')).conversations[0].unread,0);
  const reply = await chat('send',{...payload,client_id:crypto.randomUUID(),content:'GymFlow xin chào!'});
  await as(member);
  assert.equal((await chat('messages',{conversation_id:conv.id})).messages[1].id,reply.id);
  await chat('read',{conversation_id:conv.id,through:reply.sequence});
  assert.ok((await db.query('select read_at from public.messages where id=$1',[reply.id])).rows[0].read_at);
  const latest = await chat('messages',{conversation_id:conv.id,limit:1});
  assert.equal(latest.messages[0].id,reply.id);
  assert.equal((await chat('messages',{conversation_id:conv.id,before:reply.sequence,limit:1})).messages[0].id,first.id);
  await as(member);
  const activeVisit = await command('check_in', {token_hash:'b'.repeat(64)});
  const pointsBeforeCancel = Number((await db.query('select public.get_my_point_balance() as n')).rows[0].n);
  await assert.rejects(db.query('select public.gymflow_admin_cancel_membership($1)',[member]),/FORBIDDEN/);
  await db.exec('reset role');
  const orderId = (await db.query(`insert into public.membership_orders(user_id,membership_id,price_vnd_at_order,duration_days_at_order,status,approved_at,starts_at,ends_at,gym_id)
    select id,active_membership_id,300000,30,'APPROVED',now()-interval '1 day',now()-interval '1 day',membership_expires_at,home_gym_id from public.users where id=$1 returning id`,[member])).rows[0].id;
  const visitsBefore = Number((await db.query('select count(*) as n from public.gym_sessions where user_id=$1',[member])).rows[0].n);
  await as(admin);
  const cancelled = (await db.query('select public.gymflow_admin_cancel_membership($1) as data',[member])).rows[0].data;
  assert.equal(cancelled.home_gym_id,null);
  assert.equal(cancelled.has_open_session,false);
  await as(member);
  const cancelledProfile=(await db.query('select home_gym_id,membership_expires_at from public.users where id=$1',[member])).rows[0];
  assert.equal(cancelledProfile.home_gym_id,null);
  assert.equal(Number((await db.query('select public.get_my_point_balance() as n')).rows[0].n),pointsBeforeCancel);
  assert.equal(Number((await db.query('select count(*) as n from public.gym_sessions where user_id=$1',[member])).rows[0].n),visitsBefore);
  assert.ok((await db.query('select check_out_at from public.gym_sessions where id=$1',[activeVisit.session.id])).rows[0].check_out_at);
  assert.equal((await db.query('select status from public.membership_orders where id=$1',[orderId])).rows[0].status,'CANCELLED');
  await command('check_out',{session_id:activeVisit.session.id});
  await db.query("select public.gymflow_select_home_gym('q6')");
  const newOrder=await command('membership_order',{membership_id:'10000000-0000-4000-8000-000000000001',idempotency_key:crypto.randomUUID()});
  await as(admin);
  await command('admin_order',{id:newOrder.id,status:'APPROVED'});
  await as(member);
  const newVisit=await command('check_in',{token_hash:'b'.repeat(64)});
  assert.equal(newVisit.session.gym_id,'q6');
  assert.equal(newVisit.points_earned,0);
  await command('check_out',{session_id:newVisit.session.id});
  await db.exec('reset role; set role anon');
  await assert.rejects(chat('open'),/permission denied/);
});
